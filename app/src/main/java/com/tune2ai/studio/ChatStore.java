package com.tune2ai.studio;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Pattern;

/**
 * Saved conversations for the Chats list: one JSON file per chat in app-private storage, plus an
 * index (title, preview, time, message count) so the list opens without reading every chat.
 *
 * The page owns the transcript format (what it needs to redraw a chat: text, citations, tool calls,
 * timings); this class only stores it. The model-facing history lives in the SDK's chat session with
 * the same id. Plain Java with no Android types, so it is unit-tested on the JVM.
 */
final class ChatStore {
    /** Ids are generated by the page; anything else is refused, so no path can escape [dir]. */
    private static final Pattern ID = Pattern.compile("[a-z0-9_-]{1,64}");
    private static final String INDEX = "index.json";
    private static final int PREVIEW = 120;

    private final File dir;

    ChatStore(File dir) {
        this.dir = dir;
    }

    static boolean validId(String id) {
        return id != null && ID.matcher(id).matches();
    }

    /** Index entries, most recently updated first, as a JSON array. */
    synchronized String list() {
        List<JSONObject> entries = new ArrayList<>();
        JSONObject index = readIndex();
        for (java.util.Iterator<String> it = index.keys(); it.hasNext(); ) entries.add(index.optJSONObject(it.next()));
        entries.sort((a, b) -> Long.compare(b.optLong("updatedAt"), a.optLong("updatedAt")));
        return new JSONArray(entries).toString();
    }

    /** The saved chat, or "null" if there is none. */
    synchronized String load(String id) {
        if (!validId(id)) return "null";
        File f = new File(dir, id + ".json");
        if (!f.isFile()) return "null";
        try {
            return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8);
        } catch (IOException e) {
            return "null";
        }
    }

    /** Saves a chat {id, title, messages: [{role, text, at, …}], …} and updates the index. */
    synchronized void save(String json) throws JSONException, IOException {
        JSONObject chat = new JSONObject(json);
        String id = chat.getString("id");
        if (!validId(id)) throw new JSONException("Bad chat id");
        JSONArray messages = chat.optJSONArray("messages");
        if (messages == null || messages.length() == 0) return; // nothing worth keeping yet
        long updated = chat.optLong("updatedAt", System.currentTimeMillis());
        String preview = "";
        for (int i = messages.length() - 1; i >= 0 && preview.isEmpty(); i--) {
            preview = messages.getJSONObject(i).optString("text").replaceAll("[#*`>|_~\\-]+", " ").replaceAll("\\s+", " ").trim();
        }
        if (preview.length() > PREVIEW) preview = preview.substring(0, PREVIEW - 1) + "…";
        String title = chat.optString("title").trim();
        if (title.isEmpty()) title = "New chat";

        dir.mkdirs();
        write(new File(dir, id + ".json"), chat.toString());
        JSONObject index = readIndex();
        index.put(id, new JSONObject().put("id", id).put("title", title).put("preview", preview)
                .put("updatedAt", updated).put("count", messages.length()));
        write(new File(dir, INDEX), index.toString());
    }

    synchronized void rename(String id, String title) throws JSONException, IOException {
        if (!validId(id) || title == null || title.trim().isEmpty()) return;
        String raw = load(id);
        if ("null".equals(raw)) return;
        JSONObject chat = new JSONObject(raw).put("title", title.trim()).put("renamed", true);
        write(new File(dir, id + ".json"), chat.toString());
        JSONObject index = readIndex();
        JSONObject entry = index.optJSONObject(id);
        if (entry != null) {
            entry.put("title", title.trim());
            write(new File(dir, INDEX), index.toString());
        }
    }

    synchronized boolean delete(String id) throws IOException {
        if (!validId(id)) return false;
        boolean removed = new File(dir, id + ".json").delete();
        JSONObject index = readIndex();
        if (index.remove(id) != null) {
            write(new File(dir, INDEX), index.toString());
            removed = true;
        }
        return removed;
    }

    private JSONObject readIndex() {
        File f = new File(dir, INDEX);
        if (!f.isFile()) return new JSONObject();
        try {
            return new JSONObject(new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8));
        } catch (IOException | JSONException e) {
            return new JSONObject(); // damaged index: the list starts empty; chat files stay on disk
        }
    }

    /** Writes through a temp file and a rename, so a crash never leaves half a chat. */
    private static void write(File target, String content) throws IOException {
        File tmp = new File(target.getPath() + ".tmp");
        try (FileOutputStream out = new FileOutputStream(tmp)) {
            out.write(content.getBytes(StandardCharsets.UTF_8));
            out.getFD().sync();
        }
        if (!tmp.renameTo(target)) {
            target.delete();
            if (!tmp.renameTo(target)) throw new IOException("Could not save " + target.getName());
        }
    }
}
